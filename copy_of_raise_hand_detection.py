# ============================================================
# 9. MAIN REALTIME LOOP
# ============================================================

frame_count = 0
fps_timer = time.time()
fps = 0.0

try:

    while True:

        # ----------------------------------------------------
        # JS webcam frame -> Base64
        # ----------------------------------------------------

        frame_b64 = output.eval_js(
            "captureFrame()"
        )

        # ----------------------------------------------------
        # Stop condition
        # ----------------------------------------------------

        if frame_b64 == "STOP":
            break

        if frame_b64 == "WAIT":
            time.sleep(0.03)
            continue

        if not frame_b64:
            continue

        # ----------------------------------------------------
        # Remove data URL prefix
        # ----------------------------------------------------

        if "," in frame_b64:
            frame_b64 = frame_b64.split(",", 1)[1]

        # ----------------------------------------------------
        # Base64 -> bytes
        # ----------------------------------------------------

        image_bytes = base64.b64decode(
            frame_b64
        )

        # ----------------------------------------------------
        # bytes -> OpenCV image
        # ----------------------------------------------------

        np_arr = np.frombuffer(
            image_bytes,
            dtype=np.uint8
        )

        frame = cv2.imdecode(
            np_arr,
            cv2.IMREAD_COLOR
        )

        if frame is None:
            continue


        # ====================================================
        # YOLO POSE INFERENCE
        # ====================================================

        results = model(
            frame,
            imgsz=640,
            conf=0.25,
            device=DEVICE,
            verbose=False
        )

        result = results[0]


        # ====================================================
        # MULTI-PERSON PROCESSING
        # ====================================================

        person_count = 0
        raised_count = 0

        if (
            result.boxes is not None
            and result.keypoints is not None
        ):

            boxes = result.boxes.xyxy.cpu().numpy()
            person_confs = result.boxes.conf.cpu().numpy()

            kpts = result.keypoints.data.cpu().numpy()

            person_count = len(boxes)


            # ------------------------------------------------
            # Process EVERY person
            # ------------------------------------------------

            for i in range(len(boxes)):

                bbox = boxes[i]

                person_conf = float(
                    person_confs[i]
                )

                person_keypoints = kpts[i]

                raised = draw_person(
                    frame,
                    bbox,
                    person_keypoints,
                    person_conf
                )

                if raised:
                    raised_count += 1


        # ====================================================
        # FPS
        # ====================================================

        frame_count += 1

        elapsed = time.time() - fps_timer

        if elapsed >= 1.0:

            fps = frame_count / elapsed

            frame_count = 0
            fps_timer = time.time()


        # ====================================================
        # INFORMATION PANEL
        # ====================================================

        cv2.rectangle(
            frame,
            (0, 0),
            (260, 70),
            (0, 0, 0),
            -1
        )

        cv2.putText(
            frame,
            f"Persons: {person_count}",
            (10, 25),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.65,
            (255, 255, 255),
            2,
            cv2.LINE_AA
        )

        cv2.putText(
            frame,
            f"Raised: {raised_count} | FPS: {fps:.1f}",
            (10, 52),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.55,
            (0, 255, 255),
            2,
            cv2.LINE_AA
        )


        # ====================================================
        # OpenCV -> JPEG -> Base64
        # ====================================================

        success, encoded = cv2.imencode(
            ".jpg",
            frame,
            [
                int(cv2.IMWRITE_JPEG_QUALITY),
                70
            ]
        )

        if not success:
            continue

        output_b64 = base64.b64encode(
            encoded.tobytes()
        ).decode("utf-8")


        # ====================================================
        # DISPLAY PROCESSED FRAME IN COLAB
        # ====================================================

        output_handle.update(
            HTML(
                f"""
                <div style="
                    font-family:Arial;
                    margin-top:10px;
                ">

                    <div style="
                        font-weight:bold;
                        margin-bottom:8px;
                    ">
                        YOLO26 Pose - Processed Output
                    </div>

                    <img
                        src="data:image/jpeg;base64,{output_b64}"
                        style="
                            width:640px;
                            max-width:100%;
                            border-radius:8px;
                            border:1px solid #ccc;
                        "
                    >

                </div>
                """
            )
        )


        # Một chút sleep để tránh Python loop chiếm CPU tuyệt đối
        time.sleep(0.005)


except KeyboardInterrupt:

    print("Interrupted by user.")


finally:

    try:
        output.eval_js("stopWebcam()")
    except:
        pass

    print("Webcam stopped.")

