# ============================================================

def draw_person(
    frame,
    bbox,
    keypoints,
    person_conf
):
    """
    bbox: [x1, y1, x2, y2]
    keypoints: [17, 3] -> x, y, confidence
    """

    x1, y1, x2, y2 = map(int, bbox)

    # --------------------------------------------------------
    # Determine raised hand
    # --------------------------------------------------------

    raised_hand = False

    # Left hand
    if (
        keypoints[LEFT_WRIST][2] > 0.5
        and keypoints[LEFT_SHOULDER][2] > 0.5
    ):

        wrist_y = keypoints[LEFT_WRIST][1]
        shoulder_y = keypoints[LEFT_SHOULDER][1]

        if wrist_y < shoulder_y:
            raised_hand = True

    # Right hand
    if (
        keypoints[RIGHT_WRIST][2] > 0.5
        and keypoints[RIGHT_SHOULDER][2] > 0.5
    ):

        wrist_y = keypoints[RIGHT_WRIST][1]
        shoulder_y = keypoints[RIGHT_SHOULDER][1]

        if wrist_y < shoulder_y:
            raised_hand = True


    # --------------------------------------------------------
    # Bounding box color
    # --------------------------------------------------------

    if raised_hand:

        # RED - OpenCV uses BGR
        bbox_color = (0, 0, 255)

    else:

        # GREEN
        bbox_color = (0, 255, 0)


    # --------------------------------------------------------
    # Bounding box
    # --------------------------------------------------------

    cv2.rectangle(
        frame,
        (x1, y1),
        (x2, y2),
        bbox_color,
        2
    )


    # --------------------------------------------------------
    # Person confidence
    # --------------------------------------------------------

    conf_text = f"Person {person_conf:.2f}"

    cv2.putText(
        frame,
        conf_text,
        (x1, max(20, y1 - 8)),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.55,
        bbox_color,
        2,
        cv2.LINE_AA
    )


    # --------------------------------------------------------
    # HAND RAISED label
    # --------------------------------------------------------

    if raised_hand:

        label_y = max(45, y1 - 28)

        cv2.putText(
            frame,
            "HAND RAISED",
            (x1, label_y),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.65,
            (0, 0, 255),
            2,
            cv2.LINE_AA
        )


    # --------------------------------------------------------
    # Draw skeleton
    # --------------------------------------------------------

    for a, b in SKELETON:

        xa, ya, ca = keypoints[a]
        xb, yb, cb = keypoints[b]

        if ca > 0.25 and cb > 0.25:

            xa, ya = int(xa), int(ya)
            xb, yb = int(xb), int(yb)

            cv2.line(
                frame,
                (xa, ya),
                (xb, yb),
                (255, 255, 0),
                2,
                cv2.LINE_AA
            )


    # --------------------------------------------------------
    # Draw keypoints (Bỏ qua 5 điểm trên mặt: 0=mũi, 1,2=mắt, 3,4=tai)
    # --------------------------------------------------------

    for idx in range(5, len(keypoints)):
        x, y, conf = keypoints[idx]
        if conf > 0.25:

            cv2.circle(
                frame,
                (int(x), int(y)),
                4,
                (0, 255, 255),
                -1
            )


    return raised_hand


